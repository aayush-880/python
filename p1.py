# Basic Python code example

# Print a message
print("Hello, World!")

# Variables
name = "Aayush"
age = 20

# Conditional statement
if age >= 18:
    print(f"{name} is an adult.")
else:
    print(f"{name} is not an adult.")

# Loop
for i in range(5):
    print("Iteration:", i)

# Function
def greet(person):
    return f"Hello, {person}!"

print(greet(name))
